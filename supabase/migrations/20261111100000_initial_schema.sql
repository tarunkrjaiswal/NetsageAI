create table if not exists public.cases (
    case_id text primary key,
    category text not null,
    symptom text not null,
    topology text not null,
    show_output text not null,
    expected_fault text not null,
    osi_layer text not null,
    concept text not null,
    severity text not null check (severity in ('Low', 'Medium', 'High', 'Critical'))
);

create table if not exists public.diagnoses (
    id bigint generated by default as identity primary key,
    case_ref text,
    category text,
    symptom text not null,
    topology text,
    show_output text,
    root_cause text,
    osi_layer text,
    confidence text check (confidence in ('Low', 'Medium', 'High')),
    evidence text,
    next_command text,
    fix_steps text,
    rule_results text,
    ai_conflict integer default 0,
    seed_key text,
    created_at timestamp default current_timestamp
);

alter table public.diagnoses
    add column if not exists seed_key text;

create unique index if not exists idx_diagnoses_seed_key
    on public.diagnoses (seed_key)
    where seed_key is not null;

create table if not exists public.reviews (
    id bigint generated by default as identity primary key,
    diagnosis_id bigint not null references public.diagnoses(id) on delete cascade,
    decision text not null check (decision in ('accept', 'edit', 'reject')),
    human_root_cause text,
    human_correction text,
    reason text,
    verified_before text,
    fix_applied text,
    verified_after text,
    reviewed_at timestamp default current_timestamp,
    constraint one_review_per_diagnosis unique (diagnosis_id)
);

create unique index if not exists idx_reviews_one_per_diagnosis
    on public.reviews (diagnosis_id);

create or replace view public.responsible_ai_log as
select
    d.id as diagnosis_id,
    d.case_ref,
    d.category,
    d.root_cause as ai_diagnosis,
    d.confidence as ai_confidence,
    r.decision as human_decision,
    r.human_root_cause as human_diagnosis,
    r.reason,
    r.reviewed_at
from public.diagnoses d
join public.reviews r on r.diagnosis_id = d.id
where r.decision in ('edit', 'reject')
order by r.reviewed_at desc;
